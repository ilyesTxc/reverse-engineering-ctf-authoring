#!/usr/bin/env python3
"""
build.py - builds both CTF binaries.

It re-computes the five key pieces in Python (independently of keygen.c), joins them in ORDER, encodes the flag
in three levels, masks the blob with the key, writes generated.h, and compiles.

Usage:   python3 build.py                 # default flag
         FLAG='SecurinetsENIT{my_flag}' python3 build.py
"""
import base64
import codecs
import os
import shutil
import subprocess
import sys
import tempfile
import json

HERE = os.path.dirname(os.path.abspath(__file__))
FLAG = os.environ.get("FLAG", "SecurinetsENIT{th3_m4d_sm1th_h0lds_rax_1n_ch40s}")
MASK64 = (1 << 64) - 1


TABLES = [
    [0x4B, 0x3C, 0x2D, 0x1E, 0x0F, 0xF0, 0xE1, 0xD2],
    [0x91, 0x07, 0xC4, 0x5E, 0xA8, 0x23, 0x6D, 0xFB],
    [0x1F, 0x8A, 0x42, 0xD9, 0x60, 0xB7, 0x35, 0xEC],
    [0xAA, 0x55, 0x0E, 0x71, 0xC3, 0x98, 0x2B, 0x64],
    [0x7C, 0xE2, 0x19, 0xB0, 0x46, 0xD5, 0x83, 0x2F],
]
SHIFT, K1, K2, K3 = 0x35, 0x5A, 0xA7, 0x3D

# The real arrangement: key = piece ORDER[0] + piece ORDER[1] + ... (dungeons numbered 1..5).
# Change it here; keygen.c gets it through generated.h.
ORDER = [3, 5, 1, 4, 2]
# Slot i of the key is the piece XORed with smix(MASK_SEED + i) (see keygen.c).
MASK_SEED = 0x5EED1E55C0DEBA5E

# Rounds of the slow hash in task.c (about 1.3 seconds per guess at -O0)
STRETCH_ROUNDS = 600_000_000


def pieces() -> list:
    """The five pieces, as keygen.c's dungeon1..dungeon5 return them (little-endian uint64)"""
    t = TABLES
    p = [
        [(t[0][i] + SHIFT + i) & 0xFF for i in range(8)],                                   # dungeon1
        [(t[1][i] + K1) & 0xFF for i in range(8)],                                          # dungeon2
        [((c << 4) & 0xF0) | ((c >> 4) & 0x0F) for c in t[2]],                              # dungeon3
        [t[3][i] ^ ((K2 + i) & 0xFF) for i in range(8)],                                    # dungeon4
        [((t[4][i] + K3) & 0xFF) ^ (t[4][i - 1] if i else 0) for i in range(8)],            # dungeon5
    ]
    return [int.from_bytes(bytes(x), "little") for x in p]


def smix(z: int) -> int:
    z = (z + 0x9E3779B97F4A7C15) & MASK64
    z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & MASK64
    z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & MASK64
    return z ^ (z >> 31)


def slot_masks() -> list:
    return [smix((MASK_SEED + i) & MASK64) for i in range(5)]


def compute_key() -> bytes:
    """40-byte key: the five pieces in ORDER, each as 8 little-endian bytes (as in memory)"""
    p = pieces()
    out = b""
    for n, xm in zip(ORDER, slot_masks()):
        out += (p[n - 1] ^ xm).to_bytes(8, "little")
    return out


def key_text(key: bytes) -> str:
    """What the player types: each piece as 16 hex digits (the value rax shows), joined"""
    return "".join("%016x" % int.from_bytes(key[i:i + 8], "little") for i in range(0, len(key), 8))


def fnv1a(data: bytes) -> int:
    h = 0xCBF29CE484222325
    for c in data:
        h = ((h ^ c) * 0x100000001B3) & MASK64
    return h


def stretch(h: int) -> int:
    """Same slow loop as task.c. 600M rounds are far too slow in Python, so run it in C."""
    src = (
        "#include <stdint.h>\n#include <stdio.h>\n#include <stdlib.h>\n"
        "int main(int c, char **v){uint64_t h=strtoull(v[1],0,16),r;"
        "for(r=0;r<%dULL;r++){h^=h>>29;h*=0xBF58476D1CE4E5B9ULL;h^=h>>32;}"
        'printf("%%016llx\\n",(unsigned long long)h);return 0;}\n' % STRETCH_ROUNDS
    )
    with tempfile.TemporaryDirectory() as d:
        c = os.path.join(d, "s.c")
        open(c, "w").write(src)
        subprocess.run(["gcc", "-O2", c, "-o", os.path.join(d, "s")], check=True)
        out = subprocess.run([os.path.join(d, "s"), "%016x" % h], check=True,
                             capture_output=True, text=True).stdout
    return int(out, 16)


def encode_blob(flag: str) -> bytes:
    """Level 1: ROT13   Level 2: hex   Level 3: Base64"""
    lvl1 = codecs.encode(flag, "rot_13")
    lvl2 = lvl1.encode().hex()
    lvl3 = base64.b64encode(lvl2.encode())
    return lvl3


def mask(data: bytes, kb: bytes) -> bytes:
    return bytes(b ^ kb[i % len(kb)] for i, b in enumerate(data))


def write_header(key: bytes, blob: bytes) -> None:
    masked = mask(blob, key)
    arr = ", ".join("0x%02x" % b for b in masked)
    order = ", ".join(str(n - 1) for n in ORDER)
    with open(os.path.join(HERE, "generated.h"), "w") as f:
        f.write("/* generated by build.py - do not edit */\n")
        f.write("#define KEY_BYTES %d\n" % len(key))
        f.write("#define KEY_HASH 0x%016xULL\n" % stretch(fnv1a(key)))
        f.write("#define STRETCH_ROUNDS %dULL\n" % STRETCH_ROUNDS)
        f.write("#define KEY_ORDER { %s }\n" % order)
        f.write("#define KEY_SEED 0x%016xULL\n" % MASK_SEED)
        f.write("#define BLOB_LEN %d\n" % len(masked))
        f.write("static const unsigned char blob_data[BLOB_LEN] = { %s };\n" % arr)


def symbol_addresses(binary: str) -> dict:
    out = subprocess.run(["nm", binary], cwd=HERE, check=True, capture_output=True, text=True).stdout
    want = ("main", "gatekeeper", "access_granted", "print_blob", "dungeon", "table", "blob_data")
    return {l.split()[2]: "0x" + l.split()[0].lstrip("0") for l in out.splitlines()
            if len(l.split()) == 3 and l.split()[2].startswith(want)}


def compile_all() -> None:
    """Builds unstripped copies (*.unstripped, organizer only, with symbols) and the
    shipped binaries, which are stripped (Ghidra shows FUN_xxxxxxxx names)."""
    flags = ["-std=gnu11", "-O0", "-no-pie", "-fno-pie", "-fno-stack-protector", "-Wall", "-Wextra"]
    addrs = {}
    for src, out in (("keygen.c", "keygen"), ("task.c", "task")):
        if not os.path.exists(os.path.join(HERE, src)):
            print("skip %s (not written yet)" % src)
            continue
        cmd = ["gcc"] + flags + [src, "-o", out + ".unstripped"]
        print(" ".join(cmd))
        subprocess.run(cmd, cwd=HERE, check=True)
        addrs[out] = symbol_addresses(out + ".unstripped")
        shutil.copyfile(os.path.join(HERE, out + ".unstripped"), os.path.join(HERE, out))
        subprocess.run(["strip", out], cwd=HERE, check=True)
        os.chmod(os.path.join(HERE, out), 0o755)
    with open(os.path.join(HERE, "addresses.json"), "w") as f:
        json.dump(addrs, f, indent=2)


if __name__ == "__main__":
    key = compute_key()
    blob = encode_blob(FLAG)
    for n, p in enumerate(pieces(), 1):
        print("piece%d = %016x" % (n, p))
    print("order = %s   masks = %s" % (ORDER, ["%016x" % m for m in slot_masks()]))
    print("key  = %s" % key_text(key))
    print("blob = %s" % blob.decode())
    write_header(key, blob)
    compile_all()
    sys.exit(0)
